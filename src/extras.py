"""Optional extras: CSV export, change detection between runs, and a one-page dashboard."""
import csv
import hashlib
import html
import json
from pathlib import Path

from schema import Book

# Fields that describe the book. fetched_at / source_page are *when and where we looked*, not the book itself:
# refetching an unchanged page must not count as a change.
CONTENT_FIELDS = ["title", "price_text", "price_gbp", "availability_text", "in_stock", "stock_count",
                  "rating_text", "rating", "description"]


def record_hash(record: dict) -> str:
    content = {k: record.get(k) for k in CONTENT_FIELDS}
    return hashlib.sha256(json.dumps(content, sort_keys=True, ensure_ascii=False).encode()).hexdigest()[:16]


def load_previous(path: Path) -> list[dict]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        return []


def changes(previous: list[dict], current: list[dict]) -> dict:
    """Compare this run with the last books.json by canonical URL + content hash."""
    before = {r["product_url"]: record_hash(r) for r in previous}
    after = {r["product_url"]: record_hash(r) for r in current}
    return {
        "first_run": not previous,
        "new": sorted(u for u in after if u not in before),
        "changed": sorted(u for u in after if u in before and after[u] != before[u]),
        "unchanged": sum(1 for u in after if before.get(u) == after[u]),
        "gone": sorted(u for u in before if u not in after),
    }


def write_csv(path: Path, books: list[Book]) -> None:
    """Flat by nature: every field is a scalar. What had to be flattened: datetime -> ISO-8601 text, None -> empty
    cell, bool -> true/false, and descriptions keep their commas/quotes inside a properly quoted cell."""
    rows = [b.model_dump(mode="json") for b in books]
    with path.open("w", encoding="utf-8-sig", newline="") as f:  # BOM so Excel reads the £ correctly
        w = csv.DictWriter(f, fieldnames=list(Book.model_fields))
        w.writeheader()
        for r in rows:
            w.writerow({k: ("true" if v is True else "false" if v is False else "" if v is None else v)
                        for k, v in r.items()})


def write_dashboard(path: Path, books: list[Book], report: dict) -> None:
    prices = [b.price_gbp for b in books]
    ratings = {n: sum(b.rating == n for b in books) for n in range(1, 6)}
    newest = max((b.fetched_at for b in books), default=None)
    oldest = min((b.fetched_at for b in books), default=None)
    bar = "".join(f'<div class="r"><span>{"★" * n}</span><i style="width:{ratings[n] * 12}px"></i><b>{ratings[n]}</b></div>'
                  for n in range(5, 0, -1))
    failures = "".join(f"<li><code>{html.escape(f['url'])}</code> {html.escape(f['reason'])}</li>"
                       for f in report["failures"]) or "<li>none</li>"
    cheapest = min(books, key=lambda b: b.price_gbp) if books else None
    page = f"""<!doctype html><meta charset="utf-8"><title>Polite scraper: dashboard</title>
<style>body{{font:15px system-ui,sans-serif;max-width:880px;margin:32px auto;padding:0 16px;color:#16302B}}
.k{{display:grid;grid-template-columns:repeat(4,1fr);gap:12px}}.k div{{border:1px solid #cfe3dc;border-radius:10px;padding:12px}}
.k b{{display:block;font-size:26px}}.r{{display:flex;align-items:center;gap:8px;margin:3px 0}}.r span{{width:80px;color:#c9a227}}
.r i{{display:inline-block;height:12px;background:#1A7A4A;border-radius:3px}}code{{font-size:12px}}small{{color:#5d7a72}}</style>
<h1>Books to Scrape: last run</h1>
<p><small>Generated by <code>src/main.py</code> from <code>output/books.json</code> and <code>output/run-report.json</code>.</small></p>
<div class="k"><div>Records<b>{len(books)}</b></div><div>Price range<b>£{min(prices, default=0):.2f}–£{max(prices, default=0):.2f}</b></div>
<div>Average price<b>£{(sum(prices) / len(prices) if prices else 0):.2f}</b></div><div>Failed pages<b>{report['failed_pages']}</b></div></div>
<h2>Freshness</h2><p>Pages fetched from the site between <b>{oldest}</b> and <b>{newest}</b> (UTC). Last run: {report['finished_at']},
{report['network_requests']} network requests, {report['cache_hits']} cache hits, {report['duration_s']} s.</p>
<h2>Ratings</h2>{bar}
<h2>Cheapest</h2><p>{html.escape(cheapest.title) if cheapest else '-'} {f'(£{cheapest.price_gbp:.2f})' if cheapest else ''}</p>
<h2>Failures</h2><ul>{failures}</ul>"""
    path.write_text(page, encoding="utf-8")
